"""Барьер против секрета, уехавшего в репозиторий.

Репозиторий публичный: всё отслеживаемое читает кто угодно, а история остаётся
доступной и после правки файла. Поэтому утечка лечится сменой самого значения,
а этот тест лишь не даёт положить новое.

Секреты утекали трижды, и каждый раз их находил человек глазами: токен бота как
fallback в коде, тот же токен в curl-команде документации, пароли MeshCentral,
iiko и бар-ПК в инструкциях (см. docs/lessons.md). Поиск идёт по форме значения,
поэтому ловит и места, где рядом нет имени переменной.

Поиск через `git grep` по рабочему дереву: это ровно те файлы, которые уйдут в
следующий коммит, бинарные git пропускает сам (-I). Ограничение, которое стоит
помнить: неотслеживаемый файл git grep не видит, поэтому новый файл проверяется
только после `git add`.

Что НЕ покрыто (осознанно, ради нуля ложных срабатываний):
- пароль в таблице без подписи рядом (`| sshuser | значение | OK |`);
- пароль, отделённый от слова «пароль» больше чем шестью символами;
- любое значение без узнаваемой формы — короткое слово, имя собственное.
Расширять шаблоны стоит только вместе с прогоном по всему дереву: шаблон,
дающий ложные срабатывания, отключают целиком, и тогда не ловится ничего.
"""
import subprocess
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

# (имя, шаблон POSIX ERE, пути-исключения, что делать при срабатывании).
# Шаблоны записаны так, чтобы не совпадать с текстом этого файла.
PATTERNS = [
    ('Токен бота Telegram',
     r'[0-9]{6,12}:[A-Za-z0-9_-]{35}',
     [],
     'Значение хранится в .env сервера и в секрете TELEGRAM_BOT_TOKEN, '
     'порядок замены — docs/guides/secrets-rotation.md.'),

    ('Токен доступа в формате JWT',
     r'eyJ[A-Za-z0-9_-]{10,}\.eyJ[A-Za-z0-9_-]{20,}\.[A-Za-z0-9_-]{20,}',
     [],
     'Токены «Честного знака» и подобные живут в кэше вне репозитория. '
     'В примерах подпись сокращают, чтобы значение было заведомо нерабочим.'),

    # Две формы приватного ключа. Прежний вариант с якорями ^...$ пропускал обе
    # самые вероятные для проекта: ключ сервис-аккаунта Google приезжает внутри
    # JSON одной строкой с \n, а файл с ключом — с CRLF или отступом.
    ('Приватный ключ, заголовок в начале строки',
     r'^[[:space:]"\x27]*-----BEGIN [A-Z0-9 ]*PRIVATE KEY-----',
     [],
     'Ключи деплоя и сервис-аккаунтов лежат в секретах GitHub и в '
     '/srv/beer/secrets на сервере (docs/guides/google-sheets-export.md).'),

    ('Приватный ключ внутри JSON',
     r'BEGIN [A-Z0-9 ]*PRIVATE KEY-----\\n[A-Za-z0-9+/]{16}',
     [],
     'Файл google-sa.json не коммитят: он монтируется в /app/secrets:ro.'),

    ('Ключ доступа AWS',
     r'AKIA[0-9A-Z]{16}',
     [],
     'Ключ нужно отозвать у провайдера: удаления из файла недостаточно.'),

    # Пароль рядом со своей подписью: ровно та форма, в которой лежали пароли
    # MeshCentral, iiko и бар-ПК. Подпись — «арол», а не «[Пп]арол[ья]»: git
    # grep в локали C сравнивает побайтно, и скобочный набор из кириллицы
    # совпадает с одним байтом, разрывая многобайтовую букву. Зазор исключает
    # `<` и `$` (иначе срабатывало бы на <пароль> и ${PASSWORD}) и `!` (иначе
    # совпадало бы `if password != password2`). Хвост значения не допускает `*`:
    # с ним шаблон ловил markdown-выделение вроде «Пароль: **xxxxxx**».
    # tests/ исключены: фальшивые пароли в фикстурах — норма, а не утечка.
    ('Пароль рядом с подписью',
     r'(арол|[Pp]assword|PASSWORD|loginpass|passwd)'
     r'[^A-Za-z0-9<$!]{0,8}[A-Za-z][A-Za-z0-9_.-]{4,}[0-9!@#$%^&]',
     [':(exclude)tests/'],
     'Пароль меняют у сервиса, а в тексте оставляют плейсхолдер и место '
     'хранения. Порядок — docs/guides/secrets-rotation.md.'),
]

# Путь -> причина. Исключение означает «здесь секрет уже лежит и это известно»,
# поэтому каждая строка обязана быть временной и объяснённой. Сейчас пусто и
# должно таким оставаться: единственное исключение (кэш токена ЧЗ в
# chz_test/debug/token.json) снято вместе с самим файлом 21.09.2026.
# Добавлять строку сюда можно только когда секрет уже отозван, а удалить файл
# прямо сейчас нельзя; проверка ниже не даст исключению пережить свой файл.
ALLOWED = {}


def tracked_matches(pattern, excludes=()):
    """Строки отслеживаемых файлов, совпавшие с шаблоном."""
    command = ['git', 'grep', '-I', '-n', '-E', pattern, '--', '.', *excludes]
    result = subprocess.run(command, cwd=ROOT, capture_output=True, text=True)
    if result.returncode == 1:
        return []
    if result.returncode != 0:
        raise RuntimeError(result.stderr.strip() or 'git grep не отработал')
    return [line for line in result.stdout.splitlines() if line]


def location(line):
    """path:line из вывода git grep; в самой строке бывают двоеточия."""
    parts = line.split(':', 2)
    return ':'.join(parts[:2]) if len(parts) >= 2 else line


@unittest.skipUnless((ROOT / '.git').exists(), 'Нужен git-репозиторий')
class CommittedSecretsTests(unittest.TestCase):
    def test_no_secret_values_in_tracked_files(self):
        found = []
        for name, pattern, excludes, remedy in PATTERNS:
            for line in tracked_matches(pattern, excludes):
                place = location(line)
                if place.split(':')[0] in ALLOWED:
                    continue
                # Само значение не печатаем: сообщение теста попадёт в лог CI,
                # а он у публичного репозитория тоже публичный.
                found.append(f'{name}: {place} — {remedy}')
        self.assertEqual(found, [], 'Секрет в отслеживаемых файлах:\n' + '\n'.join(found))

    def test_allowlist_entries_still_point_at_tracked_files(self):
        """Исключение, пережившее свой файл, прикрывает уже не то, что задумано."""
        for path in ALLOWED:
            tracked = subprocess.run(['git', 'ls-files', '--error-unmatch', path],
                                     cwd=ROOT, capture_output=True, text=True)
            self.assertEqual(tracked.returncode, 0,
                             f'{path} больше не отслеживается — убрать строку из ALLOWED')


if __name__ == '__main__':
    unittest.main()
