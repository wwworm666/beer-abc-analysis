"""Общие настройки pytest: тесты не должны видеть боевые ключи, которые что-то ОТПРАВЛЯЮТ.

## Зачем

config.py, core/orderia_client.py и core/tuya_temperature.py при импорте зовут
load_dotenv и кладут в окружение процесса всё из локального .env — в том числе живые
токены Telegram-ботов, пароль бар-ПК, ключ Google и сессию Яндекс Бизнеса. pytest
импортирует все тестовые модули до запуска первого теста, поэтому любой тест, забывший
подменить транспорт, работал бы с настоящими ботами (2026-09-28 так фоновый поток
уведомлений об отзывах дошёл до «отправки» и остановился только на отсутствии записи —
см. docs/lessons.md).

## Как работает

Этот файл pytest загружает раньше любых тестовых модулей. Он ставит в пустую строку
переменные, через которые код что-то шлёт или пишет вовне. load_dotenv по умолчанию
(override=False) не перезаписывает переменную, которая уже есть в окружении, — даже
пустую, — поэтому боевые значения из .env в процесс тестов больше не попадают.
Тест, которому нужен «настроенный» бот, как и раньше ставит свой фиктивный токен сам.

Не трогаем: IIKO_* (отчёты только читают; ручной tests/test_all_iiko_apis.py намеренно
ходит в живой iiko, в CI .env нет вовсе) и настройки времени, путей, флагов.

Запуск одного файла без pytest (`py -3 tests/test_x.py`) этот файл не загружает — такие
тесты подменяют транспорт сами.
"""
import os

# Переменные, через которые код шлёт или пишет вовне. Причина для каждой — в комментарии.
_OUTBOUND_SECRETS = (
    'TELEGRAM_BOT_TOKEN',            # гостевой бот @kult_taplist_bot: каналы баров, рассылки гостям
    'TELEGRAM_CONTENT_BOT_TOKEN',    # отдельный бот для каналов (если задан)
    'TELEGRAM_OPEN_CHECK_BOT_TOKEN', # бот персонала: проверка открытия, тревоги, отзывы владельцу
    'TELEGRAM_GROUP_CHAT_ID',        # чат смены
    'TELEGRAM_ALARM_CHAT_IDS',       # чаты тревог
    'RECEIVING_NOTIFY_CHAT_IDS',     # чаты бухгалтерии: «приёмка на РЦ ждёт разбора» (core/receiving_notify.py)
    'REMOTE_PASS',                   # SSH на бар-ПК (remote_exec.py выполняет команды)
    'GOOGLE_SA_JSON',                # сервис-аккаунт Google: пишет в таблицу ЗП бухгалтерии
    'GOOGLE_SA_JSON_CONTENT',
    'SALARY_SHEET_ID',
    'SALARY_SHARE_WITH',
    'SALARY_SHEET_FOLDER_ID',
    'YANDEX_BUSINESS_SESSION_ID',    # кабинет Яндекс Бизнеса: каждый прогон — только с ок владельца
    'YANDEX_SEARCH_API_KEY',         # Yandex Search API (поиск картинок к постам): каждый запрос платный
    'YANDEX_SEARCH_FOLDER_ID',
)

for _name in _OUTBOUND_SECRETS:
    os.environ[_name] = ''

# Гифки к таплисту (core/taplist_gifs.py): тесты не ходят на страницы Tenor — это сеть и
# запись кэша ссылок на диск (без тома — в data/ репозитория). Тест, которому нужен поиск
# ссылки, передаёт GifSource свою поддельную функцию http_get.
os.environ['TAPLIST_GIFS_OFFLINE'] = '1'
