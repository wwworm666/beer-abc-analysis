"""Сервер бота @MCPkulturabot: работает в Амстердаме, отдельно от сайта.

Почему не на сервере сайта: сайт (beerkultura.ru) стоит в России, а API Anthropic в России
недоступен (docs/mcp.md). Поэтому разговор с Claude ведёт сервер в Амстердаме, а данные
берёт у сайта так же, как остальные ИИ-агенты владельца:

    Telegram  <->  сервер бота (Амстердам)  <->  Claude API (Anthropic)
                          |
                          +-- HTTPS -->  сайт: MCP (/mcp) — инструменты и графики
                                         API бота (/api/bot/*) — настройки, привязки, отчёт

Сайт к Anthropic не обращается. На сервере бота хранится только ключ сервера
(KULTURA_BOT_KEY — выпускает страница «Доступ агентов») и своя база (диалоги, вопросы,
расход); токен Telegram, ключ Anthropic и паузу он берёт у сайта — владелец меняет их на
странице, без входа на сервер.

Модули:

    main.py         запуск: python -m kultura_bot (переменные окружения, журнал, остановка)
    service.py      настройки с сайта, опрос Telegram, очередь чатов, ответы, отчёт сайту
    agent.py        разговор с Claude: шаги модели, инструменты, пределы, расход
    tools.py        каталог (правила и инструменты с сайта), вызовы по MCP, ask_agent
    config.py       инструкции бота и агентов (kultura_bot/prompts, kultura_bot/agents)
    site.py         связь с сайтом: API бота и MCP
    store.py        своя база (SQLite): диалоги, вопросы, расход
    claude.py       клиент Anthropic, тексты ошибок, проверка ключа, цена шага
    telegram_io.py  Telegram Bot API
    formatting.py   Markdown модели -> HTML Telegram

Кода сайта (core/, routes/) сервер бота не содержит и не импортирует: на сервере лежит
папка kultura_bot/ (частичный клон, установка — kultura_bot/deploy/install.sh).
"""
