"""Бот @MCPkulturabot: ИИ-помощник владельца сети «Культура» в Telegram.

Всё про бота — в этой папке (как устроено — README.md рядом и docs/kultura-bot.md):

    settings.py       настройки (модель, лимиты, диалог, графики) — правятся в репозитории
    prompts/bot.md    инструкции бота
    agents/*.md       агенты, которым бот поручает большие задачи по разделам
    credentials.py    секреты со страницы «Доступ агентов»: токен бота, ключ Anthropic, прокси
    access.py         кто может говорить с ботом: Telegram, привязанный к администратору сайта
    service.py        запуск вместе с сайтом: опрос Telegram, очередь разговоров, статус
    agent.py          разговор с Claude API: шаги модели, инструменты, учёт расхода
    tools.py          инструменты: все инструменты сайта (как у агентов по MCP), графики, агенты
    charts/           графики: описание, картинка, отправка, мини-приложение «Открыть интерактивно»

Пакет лёгкий при импорте: сайт (routes/, core/mcp/) берёт отсюда графики и настройки, а
тяжёлое (SDK Anthropic, поток опроса) грузится только при запуске бота.
"""


def start(app) -> None:
    """Запустить бота вместе с сайтом (app.py). Идемпотентно; работает в одном воркере.

    Сбой запуска бота сайт не роняет: он пишется в журнал сервера, сайт работает дальше."""
    try:
        from kultura_bot import service
        service.start(app)
    except Exception:  # noqa: BLE001 — бот не должен мешать сайту подняться
        import logging
        logging.getLogger('kultura-bot').exception('[KULTURA-BOT] бот не запустился')
