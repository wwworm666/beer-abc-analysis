# Предел на один вопрос в долларах — бот и его агенты вместе. Дошёл — модель больше не
# вызывает инструменты и отвечает тем, что уже узнала; в конце ответа — пометка о пределе.
# Защита от вопроса, который разросся (2026-10-20 один вопрос съел дневной предел). 0 — без
