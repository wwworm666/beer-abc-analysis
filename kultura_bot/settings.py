"""Настройки бота @MCPkulturabot — всё, что не секрет.

Меняются здесь, в репозитории: правка -> PR -> автодеплой, бот подхватывает их при
перезапуске сервиса. Секреты (токен бота Telegram, ключ Anthropic API, прокси) в
публичный репозиторий класть нельзя: владелец вставляет их один раз на странице
«Доступ агентов» (/admin/mcp), раздел «Бот @MCPkulturabot» (kultura_bot/credentials.py).

Инструкции бота — kultura_bot/prompts/bot.md, агентов — kultura_bot/agents/*.md.
Как всё устроено — docs/kultura-bot.md.
"""

# ------------------------------------------------------------------ сайт и бот

SITE_URL = 'https://beerkultura.ru'
ADMIN_PAGE_URL = SITE_URL + '/admin/mcp'      # где вставляют ключи и подключают Telegram

# Имя бота без @. Имя из getMe (его запоминает страница при сохранении токена) важнее.
BOT_USERNAME = 'MCPkulturabot'

# Отвечать ли в группах. В группе бот слушает только подключённых людей и только когда
# к нему обратились: @упоминание, ответ на его сообщение или команда /…@имя_бота.
ANSWER_IN_GROUPS = True

# ------------------------------------------------------------------ модель Claude

# Модель для бота и агентов. claude-opus-5-5 — умолчание Anthropic для агентов;
# claude-sonnet-5-5 вдвое дешевле, claude-haiku-5-5 — в сорок раз, но слабее на задачах
# в много шагов. Цены — PRICES_PER_MTOK ниже.
MODEL = 'claude-opus-5-5'

# Усилие: low | medium | high | xhigh | max. Чем выше, тем дольше модель думает и тем
# тщательнее проверяет цифры (и тем дороже). medium — умолчание Opus 5.5 и баланс для
# разговора; агентам с длинными задачами (зарплата месяца, контент-план) — high.
EFFORT = 'medium'
AGENT_EFFORT = 'high'

# Предел одного шага модели в токенах (не всего ответа: шаг — это кусок между вызовами
# инструментов). 16 000 — с запасом и без риска таймаута HTTP.
MAX_TOKENS = 16000

# Сколько шагов с инструментами разрешено на один вопрос (бот) и на одно поручение
# (агент). Защита от зацикливания; разумному вопросу хватает 5–15.
MAX_TOOL_ROUNDS = 30
AGENT_MAX_TOOL_ROUNDS = 40

# Ответ агента боту длиннее этого — обрезается (агент отчитывается выводами и таблицей,
# а не сырыми данными).
AGENT_ANSWER_MAX_CHARS = 20000

# Запасная модель Anthropic, если основная откажет по правилам безопасности (ложное
# срабатывание на безобидный вопрос): параметр fallbacks="default" Messages API.
REFUSAL_FALLBACK = True

# ------------------------------------------------------------------ диалог

# Через сколько минут тишины начинается новый диалог: прошлый разговор модель больше не
# видит, а ответ начинается с NEW_DIALOG_NOTICE. /new — новый диалог сразу.
DIALOG_IDLE_MINUTES = 120
NEW_DIALOG_NOTICE = 'Прошло много времени с прошлого вопроса, начинаю новый диалог.'

# Длинный диалог с большими ответами инструментов дорожает с каждым вопросом. Когда
# контекст переваливает за CONTEXT_CLEAR_AT_TOKENS, Anthropic вычищает старые ответы
# инструментов (context editing); вопросы, ответы бота и последние
# CONTEXT_KEEP_TOOL_RESULTS ответов инструментов остаются.
CONTEXT_CLEAR_AT_TOKENS = 80000
CONTEXT_KEEP_TOOL_RESULTS = 6

# Сколько разговоров (чатов) бот ведёт одновременно; остальные ждут очереди.
MAX_PARALLEL_DIALOGS = 2

# ------------------------------------------------------------------ деньги

# Дневной предел расхода на Claude API в долларах (оценка по токенам и ценам ниже).
# Предел исчерпан — бот отвечает «лимит на сегодня» до полуночи МСК. 0 — без предела.
DAILY_BUDGET_USD = 15.0

# Цены Anthropic за 1 млн токенов: вход, выход, чтение из кэша, запись в кэш (5 минут).
# Источник — прайс Anthropic, октябрь 2026. Модель не из списка считается по MODEL.
# claude-opus-5 и claude-opus-4-8 — запасные модели REFUSAL_FALLBACK: если ответила одна из
# них, шаг считается по её цене. Haiku 5.5 — до 100 тыс. токенов запроса (длиннее — дороже).
PRICES_PER_MTOK = {
    'claude-opus-5-5': (4.00, 20.00, 0.20, 5.00),
    'claude-sonnet-5-5': (2.00, 10.00, 0.20, 2.50),
    'claude-haiku-5-5': (0.10, 0.50, 0.01, 0.125),
    'claude-opus-5': (5.00, 25.00, 0.50, 6.25),
    'claude-opus-4-8': (5.00, 25.00, 0.50, 6.25),
}

# ------------------------------------------------------------------ инструменты сайта

# У бота все инструменты сайта (те же, что у агентов по MCP), но модель видит сразу
# только эти; остальные находит поиском по описаниям (tool search Anthropic) — так в
# каждый запрос не уходят описания двух с половиной сотен инструментов.
ALWAYS_LOADED_TOOLS = ('common_chart_send', 'common_whoami', 'common_bars_reference',
                       'common_docs_read', 'common_instructions')

# Инструменты сайта, которых у бота нет: сообщение владельцу через бота проверки
# открытия баров — бот и так отвечает в чате.
HIDDEN_TOOLS = ('common_notify_owner',)

# ------------------------------------------------------------------ графики

# Кнопка «Открыть интерактивно» под графиками.
CHART_BUTTON = True

# Короткое имя мини-приложения из @BotFather (/newapp) — только для кнопки в группах:
# там работают лишь ссылки t.me/<бот>/<имя>. Пусто — в группах график без кнопки.
MINIAPP_SHORT_NAME = ''

# Страница мини-приложения (её открывает кнопка в личке).
MINIAPP_URL = SITE_URL + '/tg/chart'

# Графиков в сутки (МСК) на все подключения — защита от зацикленного агента.
CHART_DAILY_LIMIT = 100

# ------------------------------------------------------------------ файлы от людей

# Фото и PDF из сообщения бот показывает модели. Файл больше — просит прислать меньше.
INPUT_FILE_MAX_BYTES = 10 * 1024 * 1024
