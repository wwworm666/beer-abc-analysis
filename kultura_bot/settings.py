ANSWER_IN_GROUPS = True

# ------------------------------------------------------------------ модель Claude

# Модель для бота и агентов. claude-opus-5-5 — умолчание Anthropic для агентов;
# claude-sonnet-5-5 вдвое дешевле, claude-haiku-5-5 — в сорок раз, но слабее на задачах
# в много шагов. Цены — PRICES_PER_MTOK ниже.
MODEL = 'claude-opus-5-5'

# Усилие: low | medium | high | xhigh | max. Чем выше, тем дольше модель думает и тем
# тщательнее проверяет цифры (и тем дороже: на xhigh рассуждения и ответы заметно длиннее,
# чем на medium — умолчании Opus 5.5). Решение владельца 2026-10-20: xhigh — и боту, и
# агентам (зарплата месяца, контент-план).
EFFORT = 'xhigh'
AGENT_EFFORT = 'xhigh'

# Быстрый режим Anthropic (fast mode): та же модель и тот же ум, вывод до 2,5 раза быстрее,
# цена вдвое выше (FAST_PRICE_MULTIPLIER ниже). Решение владельца 2026-10-20. Быстрый режим
# не ответил (нет мощности — 429, сбой, отказ именно в нём) — тот же шаг сразу идёт на
# обычной скорости, и FAST_COOLDOWN_S секунд бот быстрый режим не просит: у быстрого режима
# свой предел частоты, а каждая смена скорости — промах кэша. False — всегда обычная скорость.
FAST_MODE = True
FAST_COOLDOWN_S = 600

# Предел одного шага модели в токенах: рассуждения плюс текст или вызовы инструментов (шаг —
# кусок между вызовами инструментов, не весь ответ). На xhigh рассуждения длинные — 64 000 с
# запасом; запрос идёт потоком, поэтому длинный шаг не упирается в таймаут HTTP.
MAX_TOKENS = 64000

# Сколько шагов с инструментами разрешено на один вопрос (бот) и на одно поручение
# (агент). Защита от зацикливания; разумному вопросу хватает 5–15.
MAX_TOOL_ROUNDS = 30
AGENT_MAX_TOOL_ROUNDS = 40

# Ответ агента боту длиннее этого — обрезается (агент отчитывается выводами и таблицей,
# а не сырыми данными).
AGENT_ANSWER_MAX_CHARS = 20000

# Запасная модель Anthropic, если основная откажет по правилам безопасности (ложное
# срабатывание на безобидный вопрос): параметр fallbacks="default" Messages API.
REFUSAL_FALLBACK = True

# ------------------------------------------------------------------ диалог

# Через сколько минут тишины начинается новый диалог: прошлый разговор модель больше не
# видит, а ответ начинается с NEW_DIALOG_NOTICE. /new — новый диалог сразу.
DIALOG_IDLE_MINUTES = 120
NEW_DIALOG_NOTICE = 'Прошло много времени с прошлого вопроса, начинаю новый диалог.'

# Чистка контекста (context editing): запрос длиннее CONTEXT_CLEAR_AT_TOKENS — Anthropic
# вычищает старые ответы инструментов, но только если уберёт не меньше
# CONTEXT_CLEAR_AT_LEAST_TOKENS; последние CONTEXT_KEEP_TOOL_RESULTS ответов инструментов,
# вопросы и ответы бота остаются. Каждая чистка ломает кэш: весь разговор после вычищенного
# места заново пишется в кэш по цене записи. Поэтому порог высокий, а чистка редкая и
# крупная (документация Anthropic: «set the trigger high enough that clears stay infrequent,
# and clear in a few large batches»). 2026-10-20 при пороге 80 000 без минимума чистка шла
# почти на каждом шаге — один вопрос стоил $15 (docs/lessons.md).
CONTEXT_CLEAR_AT_TOKENS = 300000
CONTEXT_CLEAR_AT_LEAST_TOKENS = 150000
CONTEXT_KEEP_TOOL_RESULTS = 6

# История диалога длиннее DIALOG_MAX_CHARS символов — следующий вопрос начинает новый
# диалог. Кэш Anthropic живёт 5 минут: вопрос после паузы заново пишет в кэш всю историю,
# а большие ответы инструментов (график смен за месяц — около 65 000 символов) делают
# дорогим каждый следующий вопрос. 300 000 символов — около 100–120 тыс. токенов: запись
# такой истории в кэш ≈ $0,6 (в быстром режиме — $1,2).
DIALOG_MAX_CHARS = 300000

# Сколько разговоров (чатов) бот ведёт одновременно; остальные ждут очереди.
MAX_PARALLEL_DIALOGS = 2

# ------------------------------------------------------------------ деньги

# Дневной предел расхода на Claude API в долларах (оценка по токенам и ценам ниже).
