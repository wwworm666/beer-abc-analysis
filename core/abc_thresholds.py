"""Пороги ABC/XYZ для фасовки — в одном месте, с объяснением каждого числа.

Раньше эти константы жили копиями в core/abc_analysis.py и core/category_analysis.py
(методы `_calculate_abc_category` и `_calculate_markup_category` были побайтово
одинаковыми), и любая правка одной копии молча расходилась с другой. Здесь они
заданы один раз: страница, документация и тесты читают одни и те же числа.

Требование .claude/CLAUDE.md пункт 1: ни одного магического числа — у каждого
порога написано, откуда он взялся и что означает словами.
"""

# ==================== Парето: первая буква (выручка) ====================

# Классическое правило 80/15/5. Позиции сортируются по выручке убыв., считается
# накопленная доля: A — первые 80% денег, B — следующие 15%, C — последние 5%.
#
# Буква определяется накопленным процентом ДО позиции, а не вместе с ней.
# Разница не косметическая: позиция, ПЕРЕСЕКАЮЩАЯ порог, остаётся в младшей
# группе — той, в которую она попала бы, будь она чуть меньше. Иначе получается
# абсурд: единственный флагман с долей 90% при проверке «накоплено <= 80»
# получает B, хотя он и есть вся выручка. Делить одну позицию между двумя
# буквами в закупке нельзя, поэтому её целиком относят к группе, которую она
# добивает до порога.
PARETO_A_MAX_CUM_PERCENT = 80.0
PARETO_B_MAX_CUM_PERCENT = 95.0

# ==================== Наценка: вторая буква ====================

# Пороги АБСОЛЮТНЫЕ, а не перцентильные: при перцентилях позиция с хорошей
# наценкой получала C только потому, что рядом кто-то наценён ещё выше, и буква
# переставала быть сравнимой между периодами. 120% — МИНИМАЛЬНАЯ наценка
# фасовки в сети (владелец 2026-09-20: «120 и 250 это минималка»): ниже неё
# позиция с продажами уходит в группу «Низкая наценка · поднять цену». 100% —
# граница между B («ниже минимума, но цена выше двух себестоимостей») и C
# («ниже 100%»): буква показывает, насколько ниже минимума, а половина этого
# порога — пол правдоподобия для «Сверить учёт». Единица — ДОЛЯ: 1.2 это 120%.
MARKUP_A_MIN = 1.2
MARKUP_B_MIN = 1.0

# Те же две буквы для кегов (/draft), но со своими порогами: разлив наценивается
# втрое-вчетверо, и бутылочные 120/100 сделали бы все кеги «A». До 2026-09-20
# буква на /draft считалась по третям среди кегов разреза, и ровно треть кегов
# всегда получала C — при наценке 141-183%, которую никто не назвал бы низкой;
# буква зависела от состава недели и не сравнивалась между периодами.
#
# 250% — МИНИМАЛЬНАЯ наценка сети по разливу (владелец 2026-09-20: «розлив
# наценка 250, бутылка 120 — это минималка»); ниже неё кег с продажами уходит
# в «Низкая наценка · поднять цену». Совпадает с фактической средней за неделю
# 03-09.08.2026 (252%, 33 кега), то есть примерно половина кегов ниже минимума.
# 200% — граница между B и C: цена втрое выше себестоимости, ниже кран
# зарабатывает как бутылка, но с залогом за кег, газом и мойкой линий. На той
# же неделе пороги дают A 8 / B 14 / C 11 против принудительных 11/11/11.
KEG_MARKUP_A_MIN = 2.5
KEG_MARKUP_B_MIN = 2.0

# ==================== Решения по ассортименту ====================

# Меньше стольких продаж (штук у фасовки, порций у кегов) — спрос не измерен,
# и по нему нельзя ни хвалить, ни выводить. Ошибка оценки спроса по n
# событиям ~ 1/sqrt(n): 45% при пяти, 50% при четырёх; ниже — одна-две
# покупки, а наценка по ним может быть искажена единственной скидкой. На
# живых данных (450 фасовок, 30 дней) порог 5 оставляет 122 позиции с
# решением (61% выручки); порог 10 оставил бы 44.
MIN_SALES_FOR_VERDICT = 5

# Отрицательное решение («вывести из ассортимента») выносится только по
# периоду от четырёх полных недель. За 28 дней меньше пяти продаж исключает
# спрос от 2,3 в неделю с вероятностью 95% (Пуассон); за 14 дней тот же счёт
# у позиции со спросом 2 в неделю случается в 63% случаев — решение было бы
# монеткой. На срезе «последние 7 дней» Вайнштефан Оригинал (32 шт/мес, все
# 4 бара) показал 2 шт и без этой защиты получил бы «вывести».
MIN_DAYS_FOR_NEGATIVE_VERDICT = 28

# Ниже этой доли порога B наценка не описывает прайс, а сигналит об учёте:
# скидка до нуля, выдача сотрудникам, битая себестоимость. Половина порога —
# 50% у фасовки, 100% у кегов: так в сети не продают намеренно (самая дешёвая
# честная фасовка на живых данных 73%, самый дешёвый кег 141%; ниже — только
# 0,22-0,47 ₽ выручки за бутылку и отрицательные наценки).
MARKUP_AUDIT_FLOOR_FACTOR = 0.5

# ==================== XYZ: третья буква (стабильность спроса) ====================

# Недель С ПРОДАЖАМИ, без которых коэффициент вариации ничего не означает.
# На двух точках CV формально считается, но описывает не спрос, а пару чисел.
# То же значение и по той же причине стоит на /draft (core/draft_kegs.py).
#
# Это же условие чинит главный дефект прежнего расчёта: он требовал только двух
# недель и не проверял, что продажи в них были, поэтому позиция, проданная один
# раз, получала CV = 0% и букву X — «идеально стабильный спрос».
MIN_XYZ_WEEKS = 3

# Границы XYZ по коэффициенту вариации недельных продаж, в процентах.
# Те же значения, что на /draft, и это сознательно: одна буква должна означать
# на двух страницах одно и то же, иначе сравнивать разлив с фасовкой нельзя.
#
# Проверено на живых данных (data/beer_report.json, 4 бара, 30 дней, недельное
# окно 12.09-09.10.2025, 450 фасовок). Букву получают 111 позиций — те, что
# продавались хотя бы 3 недели из 4; у них CV от 0% до 112,2%, медиана 50,0%,
# квартили 38,5% и 69,3%. Пороги 30/60 дают X = 15%, Y = 50%, Z = 34% и читаются
# словами: до 30% — недельный объём предсказуем, свыше 60% — может отличаться
# больше чем в полтора раза. Медиана попадает в Y, то есть типичная фасовка
# честно подписана «умеренный разброс», а не загнана в крайнюю группу.
#
# Прежние 10/25 (до 2026-09-19) не выводились из данных: на этом же срезе они
# отправляли в Z подавляющее большинство позиций и различать перестали.
XYZ_X_MAX_CV = 30.0
XYZ_Y_MAX_CV = 60.0

# Длина недельной корзины. Недели считаются 7-дневными окнами, а не по календарю
# ISO: календарные недели режут произвольный период на неполные куски по краям, а
# неполная неделя даёт заниженный объём и фиктивный разброс. Тот же приём и по той
# же причине на /draft.
#
# Само окно прижато к КОНЦУ периода (core/packaging_analysis.py): период редко
# делится на 7 нацело, и отбрасывать правильнее самые старые дни, а не самые
# свежие — иначе новинка последней недели показывает «продавалась 0 недель».
WEEK_DAYS = 7

# ==================== Подписи ====================

# Стиль (DishGroup.ThirdParent) в номенклатуре iiko заполнен не у всех позиций.
# Пустое значение — не повод терять позицию из анализа, поэтому у него есть своя
# подпись, и она участвует в расчёте наравне с остальными категориями.
UNCATEGORIZED = 'Без категории (Ф)'

# То же для розлива. Стиль у кега берётся не из его собственной группы (все кеги
# лежат плоско в «Напитки Розлив / Kеги»), а с блюда-порции, которым кег
# продаётся: у блюд дерево трёхуровневое и зеркально фасовке — «Хели (Р)»
# против «Хели (Ф)». Кег без продаж в периоде и блюдо без третьего уровня
# («НОВЫЕ АЛКОГОЛЬНЫЕ БЛЮДА») остаются без категории.
UNCATEGORIZED_KEGS = 'Без категории (Р)'

# Подпись сводного разреза по всем барам. Слово одно на весь проект: так же
# называется пункт «все точки» в фильтрах /draft и /stocks.
TOTAL_LABEL = 'Общая'


def abc_letter_by_cumulative(cumulative_before_percent):
    """Буква ABC по накопленной доле ДО этой позиции (в процентах).

    На вход идёт сумма долей всех предыдущих позиций, без текущей — см.
    объяснение у PARETO_A_MAX_CUM_PERCENT. Для первой позиции это всегда 0,
    поэтому самая крупная позиция разреза гарантированно получает A.
    """
    if cumulative_before_percent < PARETO_A_MAX_CUM_PERCENT:
        return 'A'
    if cumulative_before_percent < PARETO_B_MAX_CUM_PERCENT:
        return 'B'
    return 'C'


def markup_letter(markup_share, a_min=MARKUP_A_MIN, b_min=MARKUP_B_MIN):
    """Буква ABC по наценке. markup_share — доля (1.2 = 120%), None = нет данных.

    Пороги по умолчанию — фасовки; кеги передают KEG_MARKUP_A_MIN / KEG_MARKUP_B_MIN.
    """
    if markup_share is None:
        return None
    if markup_share >= a_min:
        return 'A'
    if markup_share >= b_min:
        return 'B'
    return 'C'


def xyz_letter(cv_percent):
    """Буква XYZ по коэффициенту вариации. None = рассчитать не на чем.

    Границы включающие (<=), как на /draft: ровно 30% — ещё X.
    """
    if cv_percent is None:
        return None
    if cv_percent <= XYZ_X_MAX_CV:
        return 'X'
    if cv_percent <= XYZ_Y_MAX_CV:
        return 'Y'
    return 'Z'


# ==================== Код позиции ====================

# Знак «буквы нет» в коде: наценка без себестоимости, спрос меньше чем за
# MIN_XYZ_WEEKS недель с продажами. Не прочерк: прочерк в таблице читается как
# «пусто», а здесь пусто только одно место из трёх.
NO_LETTER = '?'


def abc_code(revenue, markup, demand):
    """Трёхбуквенный код позиции: выручка, наценка, спрос (XYZ).

    Один код на обеих страницах (/packaging и /draft). До 2026-09-26 на /draft
    третьей буквой была маржа по третям, а спрос жил отдельной колонкой XYZ:
    одинаковый на вид код значил на двух страницах разное, а колонка XYZ не
    влезала в ширину страницы. Маржа осталась отдельным полем ABC_Margin и
    показывается в карточке позиции.

    revenue — 'A' | 'B' | 'C'; markup и demand — буква или None (буквы нет).
    """
    return '{}{}{}'.format(revenue, markup or NO_LETTER, demand or NO_LETTER)
