"""Пороги ABC/XYZ для фасовки — в одном месте, с объяснением каждого числа.

Раньше эти константы жили копиями в core/abc_analysis.py и core/category_analysis.py
(методы `_calculate_abc_category` и `_calculate_markup_category` были побайтово
одинаковыми), и любая правка одной копии молча расходилась с другой. Здесь они
заданы один раз: страница, документация и тесты читают одни и те же числа.

Требование .claude/CLAUDE.md пункт 1: ни одного магического числа — у каждого
порога написано, откуда он взялся и что означает словами.
"""

# ==================== Парето: первая буква (выручка) ====================

# Классическое правило 80/15/5. Позиции сортируются по выручке убыв., считается
# накопленная доля: A — первые 80% денег, B — следующие 15%, C — последние 5%.
#
# Буква определяется накопленным процентом ДО позиции, а не вместе с ней.
# Разница не косметическая: позиция, ПЕРЕСЕКАЮЩАЯ порог, остаётся в младшей
# группе — той, в которую она попала бы, будь она чуть меньше. Иначе получается
# абсурд: единственный флагман с долей 90% при проверке «накоплено <= 80»
# получает B, хотя он и есть вся выручка. Делить одну позицию между двумя
# буквами в закупке нельзя, поэтому её целиком относят к группе, которую она
# добивает до порога.
PARETO_A_MAX_CUM_PERCENT = 80.0
PARETO_B_MAX_CUM_PERCENT = 95.0

# ==================== Наценка: вторая буква ====================

# Пороги АБСОЛЮТНЫЕ, а не перцентильные: при перцентилях позиция с хорошей
# наценкой получала C только потому, что рядом кто-то наценён ещё выше, и буква
# переставала быть сравнимой между периодами. 120% — целевая наценка фасовки в
# сети, 100% — точка, ниже которой позиция приносит меньше денег, чем стоила.
# Единица — ДОЛЯ: 1.2 это 120%.
MARKUP_A_MIN = 1.2
MARKUP_B_MIN = 1.0

# ==================== XYZ: третья буква (стабильность спроса) ====================

# Недель С ПРОДАЖАМИ, без которых коэффициент вариации ничего не означает.
# На двух точках CV формально считается, но описывает не спрос, а пару чисел.
# То же значение и по той же причине стоит на /draft (core/draft_kegs.py).
#
# Это же условие чинит главный дефект прежнего расчёта: он требовал только двух
# недель и не проверял, что продажи в них были, поэтому позиция, проданная один
# раз, получала CV = 0% и букву X — «идеально стабильный спрос».
MIN_XYZ_WEEKS = 3

# Границы XYZ по коэффициенту вариации недельных продаж, в процентах.
# Те же значения, что на /draft, и это сознательно: одна буква должна означать
# на двух страницах одно и то же, иначе сравнивать разлив с фасовкой нельзя.
#
# Проверено на живых данных (data/beer_report.json, 4 бара, 30 дней, 4 полных
# недели, 450 фасовок). Букву получают 107 позиций — те, что продавались хотя бы
# 3 недели из 4; у них CV от 0% до 135%, медиана 45,6%, квартили 34,6% и 64,2%.
# Пороги 30/60 дают X = 19%, Y = 54%, Z = 27% и читаются словами: до 30% —
# недельный объём предсказуем, свыше 60% — может отличаться больше чем в
# полтора раза. Медиана попадает в Y, то есть типичная фасовка честно подписана
# «умеренный разброс», а не загнана в крайнюю группу.
#
# Прежние 10/25 (до 2026-09-19) не выводились из данных: на этом же срезе они
# отправляли в Z 85% позиций, получивших букву, и различать перестали.
XYZ_X_MAX_CV = 30.0
XYZ_Y_MAX_CV = 60.0

# Длина недельной корзины. Недели считаются 7-дневными окнами ОТ НАЧАЛА ПЕРИОДА,
# а не по календарю ISO: календарные недели режут произвольный период на неполные
# куски по краям, а неполная неделя даёт заниженный объём и фиктивный разброс.
# Тот же приём и по той же причине на /draft.
WEEK_DAYS = 7

# ==================== Подписи ====================

# Стиль (DishGroup.ThirdParent) в номенклатуре iiko заполнен не у всех позиций.
# Пустое значение — не повод терять позицию из анализа, поэтому у него есть своя
# подпись, и она участвует в расчёте наравне с остальными категориями.
UNCATEGORIZED = 'Без категории (Ф)'

# Подпись сводного разреза по всем барам. Слово одно на весь проект: так же
# называется пункт «все точки» в фильтрах /draft и /stocks.
TOTAL_LABEL = 'Общая'


def abc_letter_by_cumulative(cumulative_before_percent):
    """Буква ABC по накопленной доле ДО этой позиции (в процентах).

    На вход идёт сумма долей всех предыдущих позиций, без текущей — см.
    объяснение у PARETO_A_MAX_CUM_PERCENT. Для первой позиции это всегда 0,
    поэтому самая крупная позиция разреза гарантированно получает A.
    """
    if cumulative_before_percent < PARETO_A_MAX_CUM_PERCENT:
        return 'A'
    if cumulative_before_percent < PARETO_B_MAX_CUM_PERCENT:
        return 'B'
    return 'C'


def markup_letter(markup_share):
    """Буква ABC по наценке. markup_share — доля (1.2 = 120%), None = нет данных."""
    if markup_share is None:
        return None
    if markup_share >= MARKUP_A_MIN:
        return 'A'
    if markup_share >= MARKUP_B_MIN:
        return 'B'
    return 'C'


def xyz_letter(cv_percent):
    """Буква XYZ по коэффициенту вариации. None = рассчитать не на чем.

    Границы включающие (<=), как на /draft: ровно 30% — ещё X.
    """
    if cv_percent is None:
        return None
    if cv_percent <= XYZ_X_MAX_CV:
        return 'X'
    if cv_percent <= XYZ_Y_MAX_CV:
        return 'Y'
    return 'Z'
