"""MCP-платформа сервиса: всё, что есть в веб-интерфейсе, доступно ИИ-агентам по MCP.

MCP (Model Context Protocol) — открытый протокол, по которому ИИ-клиент (Claude Code,
приложение Claude, расписания Claude) подключается к внешнему сервису и вызывает его
инструменты. Решение владельца (2026-09-27): по MCP доступны все данные и все
действия веб-сервиса, без обезличивания; доступ только у владельца (администратор).

Устройство:

    клиент Claude --HTTPS, Bearer-токен--> /mcp или /mcp/<домен>   (routes/mcp.py)
        -> протокол JSON-RPC MCP                                      (protocol.py)
        -> проверка токена, права на домен                             (auth.py, tokens.py, oauth.py)
        -> инструмент из реестра                                       (registry.py, tools/*.py)
        -> мост: тот же Flask-маршрут, что вызывает страница           (bridge.py)
        -> журнал вызова                                               (audit.py)

Главный принцип — ИНСТРУМЕНТ ВЫЗЫВАЕТ ТОТ ЖЕ МАРШРУТ, ЧТО И СТРАНИЦА. Мост исполняет
маршрут внутри процесса от имени владельца, поэтому цифры агента совпадают с сайтом
до копейки, а бизнес-логика не дублируется. Новый API-маршрут без инструмента или
без записи в исключениях роняет tests/test_mcp_coverage.py.

Файлы пакета:
- db.py         — SQLite mcp.db на постоянном диске (токены, OAuth, журнал, настройки)
- principal.py  — кто вызывает: владелец + токен + разрешённые домены
- spec.py       — формат описания инструмента (ToolSpec), подсказок (PromptSpec), домены
- registry.py   — сбор инструментов по доменам, инструкции для агентов
- protocol.py   — JSON-RPC и методы MCP (initialize, tools/*, prompts/*, ping)
- bridge.py     — исполнение маршрута Flask от имени владельца, упаковка ответа
- schema_check.py — проверка аргументов вызова по JSON Schema инструмента
- auth.py       — единая проверка Bearer: статический токен или OAuth, активный админ
- tokens.py     — статические токены (Claude Code)
- oauth.py      — OAuth 2.1 для приложения Claude и расписаний
- settings.py   — настройки: чат для отчётов агентов, разрешённые хосты OAuth
- audit.py      — журнал вызовов инструментов
- coverage.py   — правило покрытия: каждый API-маршрут описан инструментом или исключён
- tools/        — описания инструментов по доменам: content, stocks, analytics, staff, common

Подробно: docs/mcp.md.
"""
