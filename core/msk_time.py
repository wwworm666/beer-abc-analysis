"""Единое московское время для модулей, которые считают границы суток.

Зачем явный МСК, а не системное локальное время: в прод-образе нет системного
tzdata (каталога /usr/share/zoneinfo нет), поэтому переменная TZ=Europe/Moscow на
libc не действует и наивные date.today() / datetime.now() отдают UTC. Проверено
на проде 2026-08-12: внутри контейнера time.tzname == ('Europe', 'Europe'),
time.timezone == 0, datetime.now() показывает 22:10 при московских 01:10.

Последствие для отчётов: с 00:00 до 03:00 МСК наивный date.today() отстаёт на
календарный день. Для баров, которые работают за полночь, это ровно рабочее
время — «сегодня» на странице становится вчерашним.

Часть модулей уже обходит это явным смещением (core/open_check_bot.py,
core/iiko_api.py) или через ZoneInfo (pip-пакет tzdata в образе стоит, поэтому
ZoneInfo("Europe/Moscow") работает). Этот модуль — общая точка для тех, кому
нужна ДАТА, а не момент времени.

Фиксированное смещение +3, а не ZoneInfo: Москва не переводит часы с 2014 года,
UTC+3 действует постоянно. Так модуль не зависит от наличия tzdata вообще.

Радикальное лечение — поставить tzdata в образ, тогда наивное время станет
московским во всём приложении. Это меняет поведение всех модулей сразу
(и сдвигает время срабатывания всех шедулеров), поэтому делается отдельно и
осознанно, а не попутно. См. docs/lessons.md.
"""

from datetime import datetime, timedelta, timezone

MOSCOW_TZ = timezone(timedelta(hours=3))


def now():
    """Текущий момент по Москве (aware datetime)."""
    return datetime.now(MOSCOW_TZ)


def today():
    """Текущая московская дата."""
    return now().date()
